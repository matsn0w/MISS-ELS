import type { flashType } from "~/types/flash";
import type { Stage } from "~/types/stages";
import type { vcfConfig } from "~/types/vcfConfig";

export type VcfFormat = "stages" | "legacy";

/**
 * Builds the VCF document. "stages" is the MISS-ELS 3 format; "legacy" writes
 * the MISS-ELS 2 <PATTERN> section and only works for configurations without
 * stage-only features (see legacyIncompatibilities).
 */
export const generateVcfDocument = (
  data: vcfConfig["configuration"],
  format: VcfFormat = "stages",
) => {
  // configurator version
  const version = useRuntimeConfig().public?.version;

  // create an empty document
  const doc = document.implementation.createDocument("", "", null);

  // add comments
  const comments = [
    doc.createComment(
      " THIS FILE WAS GENERATED BY THE MISS ELS VCF CONFIGURATOR ",
    ),
    doc.createComment(" ELS VEHICLE CONFIGURATION FILE "),
    doc.createComment(
      "IF YOU DON'T KNOW WHAT YOU ARE DOING, READ THE DOCS: https://github.com/matsn0w/MISS-ELS/blob/main/docs/vcf.md",
    ),
  ];

  comments.forEach((comment) => doc.appendChild(comment));

  // create root element
  const vcfRoot = doc.createElement("vcfroot");
  vcfRoot.setAttribute("Description", data.description ?? "");
  vcfRoot.setAttribute("Author", data.author ?? "");
  vcfRoot.setAttribute("Version", version ?? "");

  doc.appendChild(vcfRoot);

  // lights
  const lights = doc.createElement("EOVERRIDE");

  data.lightables
    .filter((lightable) => lightable.type === "extra")
    .forEach((extra) => {
      let extraId = `${extra.id}`;
      extraId = extraId.replace(/(^[^\d\n]*\d[^\d\n]*$)/gm, "0$1");
      const e = doc.createElement(`Extra${extraId}`);

      if (extra.allowEnv) {
        e.setAttribute("AllowEnvLight", String(extra.allowEnv));

        if (extra.color) {
          e.setAttribute("Color", extra.color);
        }
      }

      lights.appendChild(e);
    });

  data.lightables
    .filter((lightable) => lightable.type === "misc")
    .forEach((misc) => {
      let miscId = `${misc.id}`;
      miscId = miscId.replace(/(^[^\d\n]*\d[^\d\n]*$)/gm, "0$1").toUpperCase();
      const m = doc.createElement(`Misc${miscId}`);

      if (misc.allowEnv) {
        m.setAttribute("AllowEnvLight", String(misc.allowEnv));

        if (misc.color) {
          m.setAttribute("Color", misc.color);
        }
      }

      lights.appendChild(m);
    });

  vcfRoot.appendChild(lights);

  // statics
  const statics = doc.createElement("STATIC");

  data.statics.forEach((stat) => {
    let nodeName = "";
    if (stat.type === "extra") {
      nodeName = `Extra${stat.id}`;
    } else if (stat.type === "misc") {
      nodeName = `Misc${String(stat.id).toUpperCase()}`;
    }

    const s = doc.createElement(nodeName);
    s.setAttribute("Name", stat.name ?? nodeName);

    statics.appendChild(s);
  });

  vcfRoot.appendChild(statics);

  // sounds
  const sounds = doc.createElement("SOUNDS");

  data.sounds.forEach((option) => {
    const o = doc.createElement(option.name);
    o.setAttribute("AllowUse", String(option.allowUse));

    if (option.allowUse && option.audioString) {
      o.setAttribute("AudioString", option.audioString);
    }

    if (option.allowUse && data.useServerSirens && option.soundSet) {
      o.setAttribute("SoundSet", option.soundSet);
    }

    // MISS-ELS 3 only (#179); MISS-ELS 2 does not know this attribute
    if (option.allowUse && option.interruptSiren && format === "stages") {
      o.setAttribute("InterruptSiren", "true");
    }

    sounds.appendChild(o);
  });

  vcfRoot.appendChild(sounds);

  if (format === "legacy") {
    vcfRoot.appendChild(legacyPatterns(doc, data.stages));
  } else {
    vcfRoot.appendChild(stagesElement(doc, data.stages));
  }

  // return the document
  return doc;
};

const sortedExtras = (ids: number[]) =>
  [...ids].sort((a, b) => a - b).join(",");
const sortedMiscs = (ids: string[]) => [...ids].sort().join(",");

const setLights = (
  element: Element,
  lights: Pick<flashType, "extras" | "miscs">,
) => {
  if (lights.extras.length) {
    element.setAttribute("Extras", sortedExtras(lights.extras));
  }
  if (lights.miscs.length) {
    element.setAttribute("Miscs", sortedMiscs(lights.miscs));
  }
};

const setStageOptions = (element: Element, stage: Stage) => {
  element.setAttribute("IsEmergency", String(stage.isEmergency));
  element.setAttribute("FlashHighBeam", String(stage.flashHighBeam));
  element.setAttribute("EnableWarningBeep", String(stage.enableWarningBeep));
};

const appendFlashes = (
  doc: Document,
  parent: Element,
  flashes: flashType[],
) => {
  flashes.forEach((flash) => {
    const f = doc.createElement("Flash");
    if (flash.duration) f.setAttribute("Duration", String(flash.duration));
    setLights(f, flash);
    parent.appendChild(f);
  });
};

const stagesElement = (doc: Document, stages: Stage[]) => {
  const root = doc.createElement("STAGES");

  stages.forEach((stage, index) => {
    const s = doc.createElement("Stage");
    s.setAttribute("Number", String(index + 1));
    if (stage.name.trim()) s.setAttribute("Name", stage.name.trim());
    setStageOptions(s, stage);
    setLights(s, stage);

    stage.patterns.forEach((pattern) => {
      const p = doc.createElement("Pattern");
      appendFlashes(doc, p, pattern.flashes);
      s.appendChild(p);
    });

    root.appendChild(s);
  });

  return root;
};

const legacyPatterns = (doc: Document, stages: Stage[]) => {
  const root = doc.createElement("PATTERN");

  LEGACY_PATTERNS.forEach((legacy, index) => {
    const stage = stages[index];
    if (!stage) return;

    const p = doc.createElement(legacy.element);
    setStageOptions(p, stage);
    appendFlashes(doc, p, stage.patterns[0]?.flashes ?? []);
    root.appendChild(p);
  });

  return root;
};
